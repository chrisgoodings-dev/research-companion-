/** Escape text before it is placed inside an HTML template string.
 *  Paper metadata from external APIs is untrusted, so everything dynamic goes through this. */
export function esc(value) {
  return String(value ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}
